import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';

type SidebarItemConfig = Extract<SidebarsConfig[string], unknown[]>[number];

const excludedFromAutogeneratedSidebars = [
  'using-codebolt/features-overview',
  'build-on-codebolt/building-integrations/cicd-integration',
  'build-on-codebolt/building-integrations/ide-integration',
];

function doc(label: string, id: string): SidebarItemConfig {
  excludedFromAutogeneratedSidebars.push(id);
  return {type: 'doc', label, id};
}

// Use a reference when the page belongs to another section.
function ref(label: string, id: string): SidebarItemConfig {
  return {type: 'ref', label, id};
}

function jump(label: string, path: string, heading: string): SidebarItemConfig {
  return {type: 'link', label, href: `/docs/${path}#${heading}`};
}

function group(label: string, items: SidebarItemConfig[]): SidebarItemConfig {
  return {type: 'category', label, items};
}

function directory(dirName: string): SidebarItemConfig {
  return {type: 'autogenerated', dirName};
}

function remaining(dirName: string): SidebarItemConfig {
  return {type: 'autogenerated', dirName, customProps: {excludeDocIds: excludedFromAutogeneratedSidebars}};
}

